package oop;

public class Casting {

    public static void main(String[] args) {

        // simple casting with primitive types
        double x = 10.5;
        int y = (int) x; // 10

        /*
        * it is also used with class and inheritances
        * generalClass myClass = new specificClass();
        * specificClass myNewClass = (specificClass) myClass;
        */

    }
}
